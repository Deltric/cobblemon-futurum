package com.cobblemon.mod.common.mixin.client;

import com.cobblemon.mod.common.client.render.item.CobblemonItemModelSelection;
import net.minecraft.client.renderer.item.ItemModelResolver;
import net.minecraft.client.renderer.item.ItemStackRenderState;
import net.minecraft.resources.Identifier;
import net.minecraft.world.entity.ItemOwner;
import net.minecraft.world.item.ItemDisplayContext;
import net.minecraft.world.item.ItemStack;
import net.minecraft.world.level.Level;
import org.jspecify.annotations.Nullable;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.injection.At;
import org.spongepowered.asm.mixin.injection.ModifyVariable;

@Mixin(ItemModelResolver.class)
public abstract class ItemRendererMixin {
    @ModifyVariable(method = "appendItemLayers", at = @At("STORE"), ordinal = 0)
    private @Nullable Identifier cobblemon$selectModel(@Nullable Identifier original, ItemStackRenderState output,
            ItemStack stack, ItemDisplayContext context, @Nullable Level level, @Nullable ItemOwner owner, int seed) {
        return CobblemonItemModelSelection.select(original, stack, context, owner);
    }
}
